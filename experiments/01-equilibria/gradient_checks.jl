# gradient_checks.jl — discriminating check: released ∇measure vs FD of its
# own returned measure, and probe ∇Ψ adjoint vs FD (moving boundaries).
#
# Run (pinned env, one process, one thread):
#   JULIA_DEPOT_PATH=<worktree>/.julia-depot JULIA_NUM_THREADS=1 \
#   OPENBLAS_NUM_THREADS=1 OMP_NUM_THREADS=1 \
#   <pinned julia> --project=pkgenv gradient_checks.jl [--out-dir DIR]
#
# Design (regular settings: SN model, θ = (1,-1), folds at ±0.3849 well
# inside the window [-2,2], |P| = 2 stable, no degenerate crossings):
#
#  A. released ∇measure (called DIRECTLY — the |P|=|D| loss path never
#     exercises it) vs central FD of the continuum functional it claims to
#     differentiate: M_full(θ) = ∫ w_erf(p)·φ_code·ds over the analytic
#     curve (exact SpecialFunctions.erf, kink-split Simpson).
#  B. FD of the ACTUAL RETURNED discrete measure (fresh deflationContinuation
#     per θ±h, measure summed over its states·ds) vs the continuum
#     derivative — the discretization derivative vs continuum derivative
#     distinction; swept over FD step h and continuation step ds.
#  C. M_trunc: the same erf integrand restricted to the physical window
#     intersections recomputed per θ (endpoint motion included in its FD;
#     the released adjoint carries no endpoint terms — the erf window is the
#     released mechanism, and erf is NOT exactly zero at the branch cut).
#  D. probe side (hard assertions): sn_dΦint integrand partials vs numeric
#     θ-derivatives, and ∇Ψ_sn (analytic Leibniz adjoint with moving
#     window-intersection endpoints) vs FD of Ψ; boundary terms required.
#
# Gate A/B mismatches are RETAINED AS RESULTS (the original package is not
# modified). Script exits nonzero on: probe-machinery assertion failures,
# ∇measure/continuation exceptions in required computations, or NaN in
# required outputs — not on honest gate outcomes, which are recorded with
# declared criteria in the artifacts.

