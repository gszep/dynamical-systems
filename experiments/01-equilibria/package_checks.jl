# package_checks.jl — original-package reproduction checks (needs pkgenv)
#
# Runs with the pinned package environment:
#   JULIA_DEPOT_PATH=<worktree>/.julia-depot JULIA_NUM_THREADS=1 \
#   OPENBLAS_NUM_THREADS=1 OMP_NUM_THREADS=1 \
#   <pinned julia> --project=pkgenv package_checks.jl
#
# 1. Cross-validates the stdlib probe reimplementations (src/EquilibriaProbes.jl)
#    against the actual released BifurcationInference.jl v0.1.4 @ 534ee7c:
#      velocity (Eq 10), tangent_field, measure (sinh form + erf window),
#      errors (squared distances), mean empty-set semantics, window_function.
# 2. Runs the package's own full pipeline (deflationContinuation -> loss/∇loss)
#    on the paper's minimal saddle-node model and compares against the probes.
# 3. Attempts the package tiny train! run (Flux Descent(0.01), the paper's §3.1
#    optimiser setting for the minimal models).
# Unexpected mismatches exit nonzero. Package-internal failures are recorded
# as evidence with their exact error, not silently ignored.

using LinearAlgebra
using StaticArrays
using SpecialFunctions: erf
using TOML
using Printf
using Flux: Descent, update!
using BifurcationInference
using BifurcationInference: tangent_field, measure, errors, mean,
    window_function, deflationContinuation, train!, getParameters, loss, ∇loss

const BI = BifurcationInference

include(joinpath(@__DIR__, "src", "EquilibriaProbes.jl"))
using .EquilibriaProbes

const RESULTS = joinpath(@__DIR__, "..", "..", "results", "01-equilibria")
mkpath(RESULTS)

"SN folds via probe augmented Newton from analytic warm starts."
function sn_folds_probes(θ)
    outv = Vector{Float64}[]
    for σ in (+1, -1)
        u, p = sn_fold(θ, σ)
        z, ok = solve_augmented(SNModel(), [u, p], θ)
        ok && push!(outv, z)
    end
    return outv
end

"Make a value TOML-serialisable (NaN/Inf -> strings, recursively)."
function toml_safe(x)
    x isa AbstractDict && return Dict{String,Any}(string(k) => toml_safe(v) for (k, v) in x)
    x isa AbstractVector && return [toml_safe(v) for v in x]
    x isa Real && return (isnan(x) ? "NaN" : (isinf(x) ? (x > 0 ? "Inf" : "-Inf") : x))
    x === nothing && return "nothing"
    return x
end

function write_toml(name, dict)
    open(joinpath(RESULTS, name), "w") do io
        Base.println(io, "# generated by experiments/01-equilibria/package_checks.jl")
        TOML.print(io, toml_safe(dict); sorted=true)
    end
end

T0 = time()
out = Dict{String,Any}()
failures = String[]

# ---- minimal saddle-node model in the package interface (README pattern) ----
F_sn(z::BorderedArray, θ::AbstractVector) = F_sn(z.u, (θ=θ, p=z.p))
function F_sn(u::AbstractVector, parameters::NamedTuple)
    @unpack θ, p = parameters
    f = p + θ[1]*first(u) + θ[2]*first(u)^3
    F = similar(u, typeof(f))
    F[1] = f
    return F
end

θ₀ = SizedVector{2}(1.0, -1.0)          # inference start (probes use the same)
θ_true = SizedVector{2}(2.5, -1.0)
pmin, pmax = -2.0, 2.0
grid = pmin:0.02:pmax
# targets = folds of θ_true (analytic: ±(5/3)√(5/6))
t_analytic = (5/3)*sqrt(5/6)
targets = [-t_analytic, t_analytic]
X = StateSpace(1, grid, targets)
parameters = (θ=θ₀, p=minimum(X.parameter))

# ================= 1. point-level cross-checks =================
u0, p0 = sn_fold(Vector(θ₀), +1)        # fold of θ₀ from analytic reference
z_fold = BorderedArray(SizedVector{1}(u0), p0)

# (a) velocity (Eq 10) vs analytic (-u*, -u*³) and vs probe Eq 10
v_pkg = collect(BI.velocity(F_sn, z_fold, Vector(θ₀)))
v_ana = sn_velocity_analytic(Vector(θ₀), +1)
v_prb = velocity(SNModel(), [u0, p0], Vector(θ₀))
err_v = norm(v_pkg - v_ana)
err_vp = norm(v_pkg - v_prb)
push!(out, "velocity_pkg" => v_pkg)
push!(out, "velocity_analytic" => v_ana)
push!(out, "velocity_probe" => v_prb)
push!(out, "velocity_err_pkg_vs_analytic" => err_v)
push!(out, "velocity_err_pkg_vs_probe" => err_vp)
err_v > 1e-8 && push!(failures, "velocity mismatch: $err_v")

# (b) tangent_field vs probe SVD nullspace (sign-agnostic)
u_g = 0.3                              # generic curve point of θ₀
z_g = curve_points(SNModel(), u_g, Vector(θ₀))
z_g_pkg = BorderedArray(SizedVector{1}(z_g[1]), z_g[2])
t_pkg = let b = tangent_field(F_sn, z_g_pkg, Vector(θ₀))
    [collect(b.u); b.p]
end
t_prb, σmin, _ = tangent_unit(SNModel(), z_g, Vector(θ₀))
tdot = abs(dot(t_pkg, t_prb))
push!(out, "tangent_dot_abs" => tdot)
push!(out, "tangent_min_singular_value" => σmin)
tdot < 1 - 1e-10 && push!(failures, "tangent mismatch: |dot| = $tdot")

# (c) measure (sinh form, erf window) vs probe reimplementation
function measure_point_probe(z, θ)
    p = z[2]
    w = (1 + erf((10*(p - pmin) - 3)/sqrt(2)))/2 *
        (1 - (1 + erf((10*(p - pmax) + 3)/sqrt(2)))/2)
    return w*φ_code(SNModel(), z, θ)
end
meas_rows = []
for u_g in (0.1, u0, 0.6, 1.2)
    zg = curve_points(SNModel(), u_g, Vector(θ₀))
    zgp = BorderedArray(SizedVector{1}(zg[1]), zg[2])
    m_pkg = measure(F_sn, zgp, Vector(θ₀), X)
    m_prb = measure_point_probe(zg, Vector(θ₀))
    push!(meas_rows, [u_g, m_pkg, m_prb, abs(m_pkg - m_prb)])
end
worst_meas = maximum(r[4] for r in meas_rows)
push!(out, "measure_worst_absdiff" => worst_meas)
worst_meas > 1e-8 && push!(failures, "measure mismatch: $worst_meas")

# (d) errors (squared distances) vs probe E_code
preds_pkg = [BorderedArray(SizedVector{1}(0.0), -0.3849),
             BorderedArray(SizedVector{1}(0.0), 0.7)]
E_pkg = errors(preds_pkg, X)
E_prb = E_code([-0.3849, 0.7], targets)
push!(out, "errors_pkg" => E_pkg)
push!(out, "errors_probe" => E_prb)
push!(out, "errors_absdiff" => abs(E_pkg - E_prb))
abs(E_pkg - E_prb) > 1e-12 && push!(failures, "errors mismatch: $(abs(E_pkg - E_prb))")

# (e) mean empty-set semantics (code reading: geometric -> 1, arithmetic -> 0)
g_empty = mean(x -> x^2, Float64[]; type=:geometric)
a_empty = mean(x -> x^2, Float64[]; type=:arithmetic)
push!(out, "mean_geometric_empty" => g_empty)
push!(out, "mean_arithmetic_empty" => a_empty)
(g_empty != 1.0 || a_empty != 0.0) &&
    push!(failures, "mean empty semantics: $g_empty, $a_empty")

# (f) window_function value at the window edge
w_edge = window_function(collect(grid), BorderedArray(SizedVector{1}(0.0), pmin))
push!(out, "window_at_pmin" => w_edge)
push!(out, "window_at_pmin_expected" => (1 + erf(-3/sqrt(2)))/2)
abs(w_edge - (1 + erf(-3/sqrt(2)))/2) > 1e-12 &&
    push!(failures, "window_function edge value mismatch")

# ================= 2. full package pipeline vs probes =================
hyper = getParameters(X)
steady_states = deflationContinuation(F_sn, X.roots, parameters, hyper)
θv = Vector(θ₀)
L_pkg, G_pkg = ∇loss(F_sn, steady_states, θv, X)
# predictions extracted exactly as the code does
preds = unique([s.z for branch ∈ steady_states for s ∈ branch if s.bif];
               atol=2*step(X.parameter))
preds_p = [z.p for z in preds]
push!(out, "pipeline_predictions_pkg" => sort(preds_p))
push!(out, "pipeline_nbranches" => length(steady_states))
zs_prb = sn_folds_probes(θv)
preds_probe = sort([z[end] for z in zs_prb])
push!(out, "pipeline_predictions_probe" => preds_probe)
push!(out, "pipeline_loss_pkg" => L_pkg)
if length(preds_p) == length(preds_probe)
    err_preds = norm(sort(preds_p) - preds_probe)
    push!(out, "pipeline_predictions_absdiff" => err_preds)
    # package predictions are continuation STATES flagged by detect_bifurcation
    # within ds = step(grid) = 0.02 of the true fold; the tolerance below is
    # half the continuation step (point-level velocity checks in section 1
    # already validated the formulas to 1e-9..1e-12 at identical inputs)
    err_preds > 0.5*step(X.parameter) &&
        push!(failures, "prediction sets differ beyond half a continuation step: $err_preds")
    # probe-side error-term gradient at the same θ (measure term off: |P|=|D|)
    vels_prb = [velocity(SNModel(), z, θv) for z in zs_prb]
    E_prb_atθ = E_code(preds_probe, targets)
    G_prb = ∇E_code(preds_probe, vels_prb, targets)
    push!(out, "pipeline_grad_pkg" => collect(G_pkg))
    push!(out, "pipeline_grad_probe_errorterm" => G_prb)
    push!(out, "pipeline_E_probe" => E_prb_atθ)
    if length(collect(G_pkg)) == length(G_prb)
        gerr = norm(collect(G_pkg) - G_prb)
        push!(out, "pipeline_grad_absdiff" => gerr)
        # the package evaluates velocity at its flagged continuation states,
        # which sit within one continuation step of the true fold
        gerr > 1e-3 && push!(failures, "gradient mismatch pkg vs probe: $gerr")
    else
        push!(out, "pipeline_grad_absdiff" => "dimension mismatch (|P| != |D| in package run: measure term active)")
    end
else
    push!(out, "pipeline_predictions_absdiff" =>
          "count mismatch: pkg=$(length(preds_p)) probe=$(length(preds_probe))")
    push!(failures, "prediction count differs: pkg=$(length(preds_p)) probe=$(length(preds_probe))")
end

# ================= 3. tiny train! run =================
tiny = Dict{String,Any}()
t_tiny = time()
global traj = nothing
oldout = stdout
rd, wr = redirect_stdout()
try
    global traj = train!(F_sn, (θ=copy(θ₀), p=minimum(X.parameter)), X;
                         iter=8, optimiser=Descent(0.01), convergence=0.02)
    tiny["status"] = "completed"
catch e
    tiny["status"] = "failed"
    tiny["error"] = sprint(showerror, e)
end
redirect_stdout(oldout)
close(wr)
tiny["stdout"] = read(rd, String)
tiny["seconds"] = round(time() - t_tiny; digits=3)
if traj !== nothing
    tiny["trajectory_theta"] = [collect(t) for t in traj]
    # final loss from the last θ
    L_last = try
        ss = deflationContinuation(F_sn, X.roots, (θ=traj[end], p=minimum(X.parameter)), hyper)
        loss(F_sn, ss, collect(traj[end]), X)
    catch
        NaN
    end
    tiny["final_loss"] = L_last
end
push!(out, "tiny_train" => tiny)

# capture first loss line as a check the loop actually optimised
m = match(r"Iteration 1\tLoss = ([-\d.eENaI+]+)", tiny["stdout"] isa AbstractString ? tiny["stdout"] : "")
push!(out, "tiny_train_first_loss" => (m === nothing ? "not found" : m[1]))

# ================= report =================
out["ok"] = isempty(failures)
out["failures"] = failures
out["package_version"] = string(pkgversion(BifurcationInference))
out["julia_version"] = string(VERSION)
out["seconds_total"] = round(time() - T0; digits=3)
write_toml("p0_package_checks.toml", out)
open(joinpath(RESULTS, "p9_tiny_run.txt"), "w") do io
    print(io, tiny["stdout"])
end
println("package checks: ", isempty(failures) ? "ALL OK" : "FAILURES:")
foreach(f -> println("  - ", f), failures)
@printf("total %.1fs\n", time() - T0)
isempty(failures) || exit(1)
